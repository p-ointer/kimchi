const hasB = (w: string) => { const c = w.charCodeAt(w.length - 1); return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0; };
export const josa = (w: string, a: string, b: string) => (hasB(w) ? a : b);

